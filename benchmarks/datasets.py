#!/usr/bin/env python3
"""Deterministic benchmark datasets, and the seeding of one per engine.

Two datasets are defined, because a single one answers only half the question:

  structured    the original pattern - category = row % 8, score = row % 100,
                amount = row * 3 and so on. Values are clustered and highly
                repetitive, which is close to the best case for run-length
                encoding, bit packing and per-block min/max metadata.

  high_entropy  every column is an independent splitmix64 stream of the row
                index. Value ranges are the same, so the benchmark predicates
                keep comparable selectivity, but nothing clusters within a
                block, so compression and zone maps have little to work with.

Both are generated from the row index alone, with no system randomness, so
SQLite, DuckDB and CybouDB are seeded with bit-identical data and their
materialization checksums can be compared bit for bit. The CybouDB side is
generated by benchmarks/bench_harness.asm, which implements the same two
generators; keep the two in step.
"""

import csv
import hashlib
import json
import math
import os
from pathlib import Path
import sqlite3
import struct
import subprocess
import time

ROOT = Path(__file__).resolve().parents[1]
EXE = ".exe" if os.name == "nt" else ""

FIXTURE_VERSION = 2
GENERATOR_VERSION = 1
SCHEMA_VERSION = 1
REQUIRED_FEATURES = 496  # PAX_MULTI(16) | MAP_SPAN(32) | PAX_RUNS(64) | PAX_TREE(128) | ZONE_MAPS(256)
FORBIDDEN_FEATURES = 512  # COMPRESSION must never enter the raw baseline
STORAGE_PROFILE = "raw-zone-v1"
MASK64 = (1 << 64) - 1

EVENTS_COLUMNS = [
    ("id", "INT64", "INTEGER", "BIGINT"),
    ("category", "INT32", "INTEGER", "INTEGER"),
    ("score", "INT32", "INTEGER", "INTEGER"),
    ("amount", "INT64", "INTEGER", "BIGINT"),
    ("active", "BOOL", "INTEGER", "BOOLEAN"),
    ("weight", "FLOAT32", "REAL", "FLOAT"),
    ("tag", "INT32", "INTEGER", "INTEGER"),
]

DATASETS = ("structured", "high_entropy", "shuffled_structured")


def splitmix64(x):
    """splitmix64's finalizer: a bijection on 64 bits, mirrored in assembly."""
    z = (x + 0x9E3779B97F4A7C15) & MASK64
    z = ((z ^ (z >> 30)) * 0xBF58476D1CE4E5B9) & MASK64
    z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & MASK64
    return (z ^ (z >> 31)) & MASK64


def as_signed(value):
    return value - (1 << 64) if value >= (1 << 63) else value


def row_structured(row):
    return (
        row,
        row % 8,
        row % 100,
        row * 3,
        1 if row % 2 else 0,
        (row % 1000) + 0.5,
        None if row % 5 == 0 else (row % 7),
    )


def row_high_entropy(row):
    base = row * 8
    tag_hash = splitmix64(base + 6)
    return (
        as_signed(splitmix64(base + 0)),
        splitmix64(base + 1) % 8,
        splitmix64(base + 2) % 100,
        as_signed(splitmix64(base + 3)),
        splitmix64(base + 4) & 1,
        (splitmix64(base + 5) % 2000) * 0.5,
        None if tag_hash % 5 == 0 else (tag_hash % 7),
    )


def make_shuffled_generator(rows):
    A = 6364136223846793005
    while math.gcd(A, rows) != 1:
        A += 2
    A_mod = A % rows
    B_mod = 1442695040888963407 % rows

    def gen(r):
        p = (r * A_mod + B_mod) % rows
        return row_structured(p)

    return gen


def get_generator(dataset, rows):
    if dataset == "structured":
        return row_structured
    if dataset == "high_entropy":
        return row_high_entropy
    if dataset == "shuffled_structured":
        return make_shuffled_generator(rows)
    raise ValueError(f"unknown dataset {dataset!r}")


def digest(dataset, rows, sample=100_000):
    """A cheap fingerprint of the generated values, for the metadata file.

    The first `sample` rows are enough to catch a generator that changed;
    hashing ten million rows in Python would cost more than the benchmark.
    """
    generator = get_generator(dataset, rows)
    sha = hashlib.sha256()
    for row in range(min(rows, sample)):
        for value in generator(row):
            if value is None:
                sha.update(b"\xbf")
            elif isinstance(value, float):
                sha.update(b"\x5a" + struct.pack("<f", value))
            else:
                sha.update(b"\x5a" + struct.pack("<q", value))
    return sha.hexdigest()


def metadata(dataset, rows):
    return {
        "fixture_version": FIXTURE_VERSION,
        "dataset": dataset,
        "generator_version": GENERATOR_VERSION,
        "rows": rows,
        "schema_version": SCHEMA_VERSION,
        "required_features": REQUIRED_FEATURES,
        "forbidden_features": FORBIDDEN_FEATURES,
        "storage_profile": STORAGE_PROFILE,
        "seed": "row index, splitmix64 finalizer, streams row * 8 + column",
        "digest_sha256": digest(dataset, rows),
        "digest_rows": min(rows, 100_000),
    }


def db_paths(db_dir, dataset, rows):
    stem = f"events_{rows}" if dataset == "structured" else f"events_{dataset}_{rows}"
    return {
        "cyboudb": db_dir / f"{stem}.cdb",
        "sqlite": db_dir / f"{stem}.sqlite",
        "duckdb": db_dir / f"{stem}.duckdb",
        "meta": db_dir / f"{stem}.json",
    }


def run_cmd(exe, *args):
    res = subprocess.run([str(exe), *map(str, args)], capture_output=True, timeout=3600)
    if res.returncode:
        raise RuntimeError(
            f"{Path(exe).name} {args[:2]} failed: "
            f"{res.stdout[:200]!r} {res.stderr[:200]!r}")
    return res.stdout


def cyboudb_feature_mask(db_path):
    if not db_path.exists():
        return 0
    try:
        with open(db_path, "rb") as handle:
            header = handle.read(24)
            if len(header) >= 24 and header[:4] == b"CybouDB":
                return struct.unpack_from("<Q", header, 16)[0]
    except Exception:
        pass
    return 0


def cyboudb_row_count(binary, db_path):
    try:
        out = run_cmd(binary, "query", db_path, "SELECT COUNT(*) FROM events").decode()
        counts = [int(l.strip()) for l in out.splitlines() if l.strip().isdigit()]
        if len(counts) == 1:
            return counts[0]
    except Exception:
        pass
    return -1


def sqlite_row_count(db_path):
    if not db_path.exists():
        return -1
    try:
        conn = sqlite3.connect(str(db_path))
        cnt = conn.execute("SELECT count(*) FROM events").fetchone()[0]
        conn.close()
        return cnt
    except Exception:
        return -1


def duckdb_row_count(db_path):
    if not db_path.exists():
        return -1
    try:
        import duckdb
        con = duckdb.connect(str(db_path), read_only=True)
        cnt = con.execute("SELECT count(*) FROM events").fetchone()[0]
        con.close()
        return cnt
    except Exception:
        return -1


def seed_cyboudb(binary, bench_harness, db_path, rows, dataset, compressed=False):
    required = REQUIRED_FEATURES | (512 if compressed else 0)
    forbidden = 0 if compressed else FORBIDDEN_FEATURES
    if db_path.exists():
        mask = cyboudb_feature_mask(db_path)
        if (mask & required) == required and not (mask & forbidden) and cyboudb_row_count(binary, db_path) == rows:
            print(f"[CybouDB]   reusing {db_path.name} ({rows:,} rows, features {mask})")
            return
        db_path.unlink(missing_ok=True)

    print(f"[CybouDB]   seeding {db_path.name} with {rows:,} {dataset} rows")
    # A leaf holds 448 rows of this schema across 4 pages of 4 KiB.
    needed_pages = max(12000, int((rows / 448) * 4 * 1.15) + 500)
    run_cmd(binary, "create-compressed" if compressed else "create-large", db_path, needed_pages, "--force")
    cols = ", ".join(f"{name} {kind}" for name, kind, _, _ in EVENTS_COLUMNS)
    run_cmd(binary, "query", db_path, f"CREATE TABLE events ({cols})")
    t0 = time.perf_counter()
    run_cmd(bench_harness, db_path, "--seed", rows, DATASETS.index(dataset))
    elapsed = time.perf_counter() - t0
    print(f"[CybouDB]   {rows:,} rows in {elapsed:.1f}s ({rows / max(elapsed, 1e-9):,.0f} rows/s)")


def seed_sqlite(db_path, rows, dataset, chunk=100_000):
    if db_path.exists():
        if sqlite_row_count(db_path) == rows:
            print(f"[SQLite] reusing {db_path.name} ({rows:,} rows)")
            return
        db_path.unlink(missing_ok=True)

    print(f"[SQLite] seeding {db_path.name} with {rows:,} {dataset} rows")
    generator = get_generator(dataset, rows)
    conn = sqlite3.connect(str(db_path))
    cur = conn.cursor()
    cur.execute("PRAGMA synchronous = OFF;")
    cur.execute("PRAGMA journal_mode = OFF;")
    cur.execute("PRAGMA page_size = 4096;")
    cols = ", ".join(f"{name} {sql}" for name, _, sql, _ in EVENTS_COLUMNS)
    cur.execute(f"CREATE TABLE events ({cols})")
    t0 = time.perf_counter()
    cur.execute("BEGIN TRANSACTION;")
    for start in range(0, rows, chunk):
        cur.executemany("INSERT INTO events VALUES (?, ?, ?, ?, ?, ?, ?)",
                        [generator(r) for r in range(start, min(start + chunk, rows))])
    conn.commit()
    conn.close()
    elapsed = time.perf_counter() - t0
    print(f"[SQLite] {rows:,} rows in {elapsed:.1f}s ({rows / max(elapsed, 1e-9):,.0f} rows/s)")


def seed_duckdb(db_path, rows, dataset, chunk=250_000):
    """Seed DuckDB from the same generator, so no engine gets its own data."""
    try:
        import duckdb
    except ImportError:
        print("[DuckDB] skipped: the duckdb Python package is not installed")
        return False

    if db_path.exists():
        if duckdb_row_count(db_path) == rows:
            print(f"[DuckDB] reusing {db_path.name} ({rows:,} rows)")
            return True
        db_path.unlink(missing_ok=True)

    print(f"[DuckDB] seeding {db_path.name} with {rows:,} {dataset} rows")
    generator = get_generator(dataset, rows)
    con = duckdb.connect(str(db_path))
    cols = ", ".join(f"{name} {duck}" for name, _, _, duck in EVENTS_COLUMNS)
    con.execute(f"CREATE TABLE events ({cols})")
    t0 = time.perf_counter()

    # Row-at-a-time INSERT costs tens of minutes at ten million rows, so the
    # values go through a temporary CSV that DuckDB loads with its own reader.
    # Every value here has an exact decimal form - the weights are multiples of
    # 0.5 - so the round trip through text does not change a single bit.
    csv_path = db_path.with_suffix(".seed.csv")
    try:
        with open(csv_path, "w", newline="", encoding="ascii") as handle:
            writer = csv.writer(handle)
            for start in range(0, rows, chunk):
                writer.writerows(
                    generator(r) for r in range(start, min(start + chunk, rows)))
        con.execute(
            f"COPY events FROM '{csv_path.as_posix()}' "
            "(FORMAT CSV, HEADER FALSE, NULLSTR '')")
    finally:
        con.close()
        csv_path.unlink(missing_ok=True)
    elapsed = time.perf_counter() - t0
    print(f"[DuckDB] {rows:,} rows in {elapsed:.1f}s ({rows / max(elapsed, 1e-9):,.0f} rows/s)")
    return True


def is_fixture_valid(paths, dataset, rows, cyboudb_binary, want_duckdb):
    if not paths["meta"].exists():
        return False
    try:
        meta = json.loads(paths["meta"].read_text())
    except Exception:
        return False

    if meta.get("fixture_version") != FIXTURE_VERSION:
        return False
    if meta.get("dataset") != dataset:
        return False
    if meta.get("generator_version") != GENERATOR_VERSION:
        return False
    if meta.get("rows") != rows:
        return False
    if meta.get("schema_version") != SCHEMA_VERSION:
        return False
    if meta.get("required_features") != REQUIRED_FEATURES:
        return False
    if meta.get("storage_profile") != STORAGE_PROFILE or meta.get("forbidden_features") != FORBIDDEN_FEATURES:
        return False

    if not paths["cyboudb"].exists():
        return False
    mask = cyboudb_feature_mask(paths["cyboudb"])
    if (mask & REQUIRED_FEATURES) != REQUIRED_FEATURES or (mask & FORBIDDEN_FEATURES):
        return False
    if cyboudb_row_count(cyboudb_binary, paths["cyboudb"]) != rows:
        return False

    if not paths["sqlite"].exists() or sqlite_row_count(paths["sqlite"]) != rows:
        return False

    if want_duckdb:
        if not paths["duckdb"].exists() or duckdb_row_count(paths["duckdb"]) != rows:
            return False

    return True


def ensure(db_dir, dataset, rows, cyboudb_binary, bench_harness, want_duckdb=True):
    """Make sure every engine holds this dataset, and record what it is."""
    if dataset not in DATASETS:
        raise ValueError(f"unknown dataset {dataset!r}")
    db_dir.mkdir(parents=True, exist_ok=True)
    paths = db_paths(db_dir, dataset, rows)
    if is_fixture_valid(paths, dataset, rows, cyboudb_binary, want_duckdb):
        mask = cyboudb_feature_mask(paths["cyboudb"])
        print(f"[fixture] reusing {paths['cyboudb'].name} ({rows:,} rows, features {mask})")
        return paths, (paths["duckdb"].exists() if want_duckdb else False)

    print(f"[fixture] cache invalidated or missing for {paths['cyboudb'].name}, reseeding...")
    for key in ("cyboudb", "sqlite", "duckdb", "meta"):
        paths[key].unlink(missing_ok=True)

    seed_cyboudb(cyboudb_binary, bench_harness, paths["cyboudb"], rows, dataset)
    seed_sqlite(paths["sqlite"], rows, dataset)
    have_duckdb = seed_duckdb(paths["duckdb"], rows, dataset) if want_duckdb else False
    paths["meta"].write_text(json.dumps(metadata(dataset, rows), indent=2) + "\n")
    return paths, have_duckdb


if __name__ == "__main__":
    import argparse

    parser = argparse.ArgumentParser(description="Seed the benchmark datasets")
    parser.add_argument("--rows", type=int, default=10_000_000)
    parser.add_argument("--dataset", choices=DATASETS, default="structured")
    parser.add_argument("--db-dir", type=Path, default=ROOT / "build" / "benchrun")
    parser.add_argument("--cyboudb", type=Path, default=ROOT / f"cyboudb{EXE}")
    parser.add_argument("--bench-harness", type=Path,
                        default=ROOT / "build" / f"bench_harness{EXE}")
    args = parser.parse_args()

    paths, _ = ensure(args.db_dir, args.dataset, args.rows, args.cdb, args.bench_harness)
    print(json.dumps(metadata(args.dataset, args.rows), indent=2))
    for key in ("cyboudb", "sqlite", "duckdb"):
        if paths[key].exists():
            print(f"{key:>7}: {paths[key].stat().st_size / 1e6:>8.1f} MB  {paths[key]}")
